/**
 * صيغ الجمع العربية للنقاط. العربية ستّ صيغ، والمستعمل منها هنا أربع:
 * لا شيء، واحد، اثنان، ثلاثة إلى عشرة، ثمّ ما فوقها بالمفرد المنصوب.
 * «3 نقاط» صواب و«11 نقاط» خطأ — والفرق يُرى.
 */
export function pointsLabel(n: number): string {
  if (n === 0) return "لا نقاط";
  if (n === 1) return "نقطة واحدة";
  if (n === 2) return "نقطتان";
  if (n >= 3 && n <= 10) return `${n} نقاط`;
  return `${n} نقطة`;
}

